def tehsil_pick(lang: str) -> str:
    """Reads the first ten tehsils with their keys (1 to 9, then 0)."""
    import json

    from . import config
    names = [v["ur"] for v in json.loads((config.BACKEND / "data" / "tehsils.json").read_text("utf-8")).values()][:10]
    nums = _NUM["pa" if lang == "pa" else "ur"]
    if lang == "pa":
        return "اپنی تحصیل چنو۔ " + "، ".join(f"{n} لئی {nums[i]}" for i, n in enumerate(names)) + " دباؤ۔"
    return "اپنی تحصیل چنیں۔ " + "، ".join(f"{n} کے لیے {nums[i]}" for i, n in enumerate(names)) + " دبائیں۔"


def prompts_for(lang: str) -> dict:
    base = dict(PROMPTS_PA if lang == "pa" else PROMPTS)
    base["tehsil_pick"] = tehsil_pick(lang)
    return base


